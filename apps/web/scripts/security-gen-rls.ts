import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve(process.cwd(), "..", "..", "supabase", "migrations", "20261110000700_security_restrictive_rls.sql");

const TABLES = [
  "profiles", "teams", "team_members", "team_invitations", "projects", "pages",
  "project_settings", "media", "contact_messages", "contact_recipients", "links",
  "redirects", "publish_history", "invoices", "subscription_terms", "payment_attempts",
  "payments", "refunds", "billing_ledger", "account_credits", "coupon_redemptions",
  "team_billing", "billing_notifications", "referrals", "referral_rewards",
  "referral_reward_events", "user_devices", "user_notices", "reminders", "security_events",
];

const lines: string[] = [];
lines.push("-- Generated by pnpm security:gen-rls. Do not edit by hand.");
lines.push("");
lines.push("do $$");
lines.push("declare");
lines.push("  t text;");
lines.push(`  tables text[] := array[${TABLES.map((t) => `'${t}'`).join(", ")}];`);
lines.push("begin");
lines.push("  foreach t in array tables loop");
lines.push("    if exists (select 1 from information_schema.tables where table_schema='public' and table_name=t) then");
lines.push("      execute format('alter table public.%I enable row level security', t);");
lines.push("      execute format('drop policy if exists tfa_required on public.%I', t);");
lines.push("      execute format('create policy tfa_required on public.%I as restrictive for all to authenticated using ((select public.session_verified())) with check ((select public.session_verified()))', t);");
lines.push("    end if;");
lines.push("  end loop;");
lines.push("end $$;");
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote restrictive RLS migration for ${TABLES.length} tables.`);
