import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cssPath = join(here, "..", "styles", "renderer.css");
const outPath = join(here, "..", "src", "css-manifest.ts");
const css = readFileSync(cssPath, "utf8");
const version = createHash("sha256").update(css).digest("hex").slice(0, 16);

const output = `// Generated by pnpm --filter @get-on/renderer build:css. Do not edit.
export const RENDERER_CSS_VERSION = "${version}";
export const RENDERER_CSS = ${JSON.stringify(css)};
`;
writeFileSync(outPath, output);
console.log(`Wrote ${outPath} (${version}, ${Buffer.byteLength(css)} bytes)`);
